"""Rule out eight-tap, seven-loss, rank-drop circulants through length 50.

Requires python-flint and a C++20 compiler. The search compiles a temporary
binary and leaves no outputs in the checkout. See seven_probe_floor.txt.
"""

import argparse
from math import isqrt
import os
from pathlib import Path
from random import Random
import subprocess
from tempfile import TemporaryDirectory, TemporaryFile

from flint import fmpz_poly, nmod_mat, nmod_poly


EXPECTED = {43: 6, 46: 132}


def is_prime(p):
    return p >= 2 and all(p % k != 0 for k in range(2, isqrt(p) + 1))


def circle_coefficients(n):
    return [-1] + [0] * (n - 1) + [1]


def factor_tables(n, p):
    circle = nmod_poly(circle_coefficients(n), p)
    t = nmod_poly([0, 1], p)
    factors = circle.factor()[1]
    assert sum(factor.degree() for factor, _ in factors) == n
    assert all(multiplicity == 1 for _, multiplicity in factors)
    tables = []
    possible = {0}
    for factor, _ in factors:
        degree = factor.degree()
        if factor == t - 1 or degree > 7:
            continue
        possible |= {total + degree for total in possible if total + degree <= 7}
        power = nmod_poly([1], p)
        table = []
        for _ in range(n):
            table.append(' '.join(str(power[i]) for i in range(degree)))
            power = (power * t) % factor
        tables.append((degree, table))
    return sorted(tables) if 7 in possible else []


def scanner_input(n):
    p = max(8, n - 6)
    fields = []
    while p**14 * (n - 1)**(n - 1) <= (8 * (n - 8))**(n - 1):
        if is_prime(p):
            if p == n:
                # In F_p the circle polynomial is (T-1)^p and H(1)=8.
                p += 1
                continue
            assert n % p != 0
            tables = factor_tables(n, p)
            if tables:
                fields.append(f'{p} {len(tables)}\n' + '\n'.join(
                    f'{degree}\n' + '\n'.join(powers) for degree, powers in tables
                ))
        p += 1
    return f'{n} {len(fields)}\n' + '\n'.join(fields) + '\n'


def singular_probes(n, p, h):
    # These seven rows are a basis for the ideal generated by h.
    basis = [[int(h[j - i]) if j >= i else 0 for j in range(n)] for i in range(7)]
    rng = Random(37)
    for _ in range(10_000):
        positions = [0, *sorted(rng.sample(range(1, n), 6))]
        minor = nmod_mat([[row[j] for j in positions] for row in basis], p)
        if minor.det() == 0:
            return positions
    raise AssertionError(f'No singular seven-probe minor found for n={n}, p={p}, h={h}')


def check_size(scanner, n, show_witnesses):
    circle = fmpz_poly(circle_coefficients(n))
    candidates = 0
    surviving_rank_test = 0
    previous_taps = None
    with TemporaryFile(mode='w+t') as output:
        subprocess.run([scanner], input=scanner_input(n), text=True, stdout=output, check=True)
        output.seek(0)
        for line in output:
            size, p, *taps = map(int, line.split())
            assert size == n and len(taps) == 8
            candidates += 1
            if previous_taps != taps:
                previous_taps = taps
                coefficients = [int(j in taps) for j in range(taps[-1] + 1)]
                ordinary_invertible = fmpz_poly(coefficients).gcd(circle).degree() == 0
            if not ordinary_invertible:
                continue
            circle_mod = nmod_poly(circle_coefficients(n), p)
            gcd = nmod_poly(coefficients, p).gcd(circle_mod)
            if gcd.degree() != 7:
                continue
            surviving_rank_test += 1
            witness = singular_probes(n, p, circle_mod // gcd)
            if show_witnesses:
                print(f'  mod {p}, taps {taps}, singular probes {witness}')
    assert surviving_rank_test == EXPECTED.get(n, 0), (n, surviving_rank_test)
    print(f'{n}: {candidates} filter hits, {surviving_rank_test} pass both rank tests, '
          'none pass the seven-probe test.', flush=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('sizes', type=int, nargs='*', help='lengths to replay, default 9 through 50')
    parser.add_argument('--show-witnesses', action='store_true')
    args = parser.parse_args()
    sizes = args.sizes or range(9, 51)
    if any(n < 9 or n > 50 for n in sizes):
        parser.error('lengths must be between 9 and 50')
    with TemporaryDirectory(prefix='eight-tap-minimum-') as directory:
        scanner = str(Path(directory) / 'scan')
        source = Path(__file__).with_name('scan_eight_tap_shapes.cpp')
        subprocess.run([os.environ.get('CXX', 'c++'), '-O3', '-std=c++20',
                        '-Wall', '-Wextra', '-pedantic', str(source), '-o', scanner], check=True)
        for n in sizes:
            check_size(scanner, n, args.show_witnesses)


if __name__ == '__main__':
    main()
