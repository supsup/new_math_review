#!/usr/bin/env python3
"""check_clock_and_shift.py [OUT.json]

The separate program behind clock_and_shift.html. For 3, 5 and 7 dots and every fixed turn it builds the shift and the
clock as p by p matrices of complex numbers, checks that the two orders differ by exactly the fixed turn, finds the group
the two matrices generate by multiplying matrices until nothing new appears, and tests that the representation cannot
be split (the average of |trace|^2 over the group is 1). It also counts the conjugacy classes of the group of triples.
Standard library only."""
# Independent numbers for the page 'A clock and a shift'. Written apart from the page's JavaScript: the page works with
# exponents of a root of unity; this program builds the actual complex matrices, multiplies them as matrices, and finds
# the group they generate and its conjugacy classes by brute force. Standard library only.
import cmath, json, sys
def mats(p, k):
    w = cmath.exp(2j * cmath.pi / p)
    X = [[1 if (r - c) % p == 1 else 0 for c in range(p)] for r in range(p)]          # X e_j = e_(j+1)
    Z = [[w ** (k * r) if r == c else 0 for c in range(p)] for r in range(p)]         # Z e_j = w^(k j) e_j
    return w, X, Z
def mul(A, B): n = len(A); return [[sum(A[i][t] * B[t][j] for t in range(n)) for j in range(n)] for i in range(n)]
def close(A, B): return all(abs(A[i][j] - B[i][j]) < 1e-9 for i in range(len(A)) for j in range(len(A)))
def key(A): return tuple((round(x.real, 6) + 0.0, round(x.imag, 6) + 0.0) for row in A for x in row)
out = {}
for p in (3, 5, 7):
    for k in range(1, p):
        w, X, Z = mats(p, k)
        ZX, XZ = mul(Z, X), mul(X, Z)
        assert close(ZX, [[w ** k * x for x in row] for row in XZ]), (p, k)          # ZX = w^k XZ
        assert not close(ZX, XZ)
        # the group generated by X and Z
        I = [[1 if i == j else 0 for j in range(p)] for i in range(p)]
        seen = {key(I): I}; frontier = [I]
        while frontier:
            nxt = []
            for A in frontier:
                for G in (X, Z):
                    B = mul(A, G); kb = key(B)
                    if kb not in seen: seen[kb] = B; nxt.append(B)
            frontier = nxt
        size = len(seen)
        norm = sum(abs(sum(A[i][i] for i in range(p))) ** 2 for A in seen.values()) / size   # 1 exactly when irreducible
        # only multiples of the identity commute with both X and Z (checked on the matrix units)
        comm = 0
        for i in range(p):
            for j in range(p):
                E = [[1 if (r, c) == (i, j) else 0 for c in range(p)] for r in range(p)]
                # count solutions is done on the page by algebra; here just record that no single unit commutes with both
                comm += close(mul(E, X), mul(X, E)) and close(mul(E, Z), mul(Z, E))
        out["%d,%d" % (p, k)] = {"size": size, "norm": round(norm, 9), "units_commuting": comm}
# conjugacy classes of the abstract group of triples (a, b, c) with (a,b,c)(a',b',c') = (a+a', b+b', c+c'+b*a') mod p
def classes(p):
    els = [(a, b, c) for a in range(p) for b in range(p) for c in range(p)]
    m = lambda g, h: ((g[0] + h[0]) % p, (g[1] + h[1]) % p, (g[2] + h[2] + g[1] * h[0]) % p)
    inv = {g: next(h for h in els if m(g, h) == (0, 0, 0)) for g in els}
    seen, n = set(), 0
    for g in els:
        if g in seen: continue
        n += 1
        for h in els: seen.add(m(m(h, g), inv[h]))
    return n
out["classes"] = {str(p): classes(p) for p in (3, 5, 7)}
json.dump(out, open(sys.argv[1] if len(sys.argv) > 1 else "expect_c.json", "w"))
print({k: v for k, v in out.items() if k in ("3,1", "5,2", "7,3")}, out["classes"])
print("all sizes are p^3:", all(v["size"] == int(k.split(",")[0]) ** 3 for k, v in out.items() if "," in k), "; all norms 1:", all(abs(v["norm"] - 1) < 1e-6 for k, v in out.items() if "," in k))
